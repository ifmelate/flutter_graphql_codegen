    });

    test('First Test', () {
      expect(awesome.isAwesome, isTrue);
      final builderOptions = BuilderOptions({
        'config_path': 'test/fixtures/graphql_codegen.yaml',
      });
      graphqlCodegenBuilder(builderOptions);
      /* builder.build(BuildStep()); */
    });
  });
}
