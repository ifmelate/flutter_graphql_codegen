import 'package:flutter_graphql_codegen/src/config_context.dart';
import 'package:flutter_graphql_codegen/src/declarations.dart';
import 'package:flutter_graphql_codegen/src/diagnostics.dart';
import 'package:flutter_graphql_codegen/src/generator.dart';
import 'package:flutter_graphql_codegen/src/type_generator.dart';
import 'package:test/test.dart';

const _schema = r'''
type User { id: ID! name: String }
input UserQuery { name: String }
type Query { user(id: ID!): User  users(first: Int): [User!]!  version: String }
type Mutation { rename(id: ID!, name: String!): User  ping: Boolean  touch(at: Int): Boolean }
type Subscription { userChanged(id: ID): User! }
''';

String _generate(String document, String name, String type) {
  final types = TypeGenerator.generateTypesFile(_schema);
  return GraphQLCodeGenerator.generateOperationFile(
      _schema, document, name, type, types);
}

const _getUser = r'query GetUser($id: ID!) { user(id: $id) { id name } }';
const _rename = r'mutation Rename($id: ID!, $name: String!) '
    r'{ rename(id: $id, name: $name) { id name } }';
const _userChanged =
    r'subscription UserChanged($id: ID) { userChanged(id: $id) { id } }';

void main() {
  setUp(() {
    CodegenConfigContext.reset();
    CodegenConfigContext.strictNullability = true;
  });
  tearDown(CodegenConfigContext.reset);

  test('nothing Flutter is generated by default', () {
    for (final (doc, name, type) in [
      (_getUser, 'GetUser', 'query'),
      (_rename, 'Rename', 'mutation'),
      (_userChanged, 'UserChanged', 'subscription'),
    ]) {
      final code = _generate(doc, name, type);
      expect(code, isNot(contains('graphql_flutter')));
      expect(code, isNot(contains('package:flutter/')));
      expect(code, isNot(contains('RunRenameMutation')));
    }
  });

  group('flutter_widgets', () {
    setUp(() => CodegenConfigContext.flutterWidgets = true);

    test('imports flutter and graphql_flutter with prefixes', () {
      final code = _generate(_getUser, 'GetUser', 'query');
      expect(code,
          contains("import 'package:flutter/widgets.dart' as widgets;\n"));
      expect(
          code,
          contains("import 'package:graphql_flutter/graphql_flutter.dart' "
              'as graphql_flutter;\n'));
    });

    test('a query gets a widget wrapping Query with the typed options', () {
      final code = _generate(_getUser, 'GetUser', 'query');
      expect(code,
          contains('class GetUserQuery extends widgets.StatelessWidget {\n'));
      expect(
          code,
          contains('  const GetUserQuery({\n'
              '    super.key,\n'
              '    required this.variables,\n'
              '    this.fetchPolicy,\n'));
      expect(code, contains('  final GetUserVariables variables;\n'));
      expect(code, contains('  final graphql.OnQueryComplete? onComplete;\n'));
      expect(code, contains('  final graphql.GraphQLClient? client;\n'));
      expect(
          code,
          contains('  final graphql_flutter.QueryBuilder<GetUser_User?> '
              'builder;\n'));
      expect(
          code,
          contains('    final options = getUserQueryOptions(\n'
              '      variables,\n'
              '      fetchPolicy: fetchPolicy,\n'));
      // The widget's field, not build's BuildContext.
      expect(code, contains('      context: this.context,\n'));
      expect(
          code,
          contains('      return graphql_flutter.Query<GetUser_User?>'
              '(options: options, builder: builder);\n'));
      expect(code, contains('graphql_flutter.QueryOnClient<GetUser_User?>('));
      expect(code, isNot(contains('useGetUserQuery')));
    });

    test('optional and no variables', () {
      final users = _generate(
          r'query Users($first: Int) '
              r'{ users(first: $first) { id } }',
          'Users',
          'query');
      expect(users, contains('    this.variables,\n'));
      expect(users, contains('  final UsersVariables? variables;\n'));
      expect(
          users,
          contains('    final options = usersQueryOptions(\n'
              '      variables: variables,\n'));

      final version =
          _generate('query Version { version }', 'Version', 'query');
      expect(version, isNot(contains('variables;')));
      expect(
          version,
          contains('    final options = versionQueryOptions(\n'
              '      fetchPolicy: fetchPolicy,\n'));
    });

    test('a trailing operation kind is not repeated', () {
      final query = _generate(
          r'query GetUserQuery($id: ID!) '
              r'{ user(id: $id) { id } }',
          'GetUserQuery',
          'query');
      expect(query, contains('class GetUserQuery extends'));
      expect(query, isNot(contains('GetUserQueryQuery')));

      final mutation = _generate(
          'mutation PingMutation { ping }', 'PingMutation', 'mutation');
      expect(mutation, contains('class PingMutation extends'));
      expect(mutation, contains('typedef RunPingMutation ='));

      // A name that is only the kind keeps it.
      final bare = _generate('query Query { version }', 'Query', 'query');
      expect(bare, contains('class QueryQuery extends'));
    });

    test('a mutation gets a widget with a typed run function', () {
      final code = _generate(_rename, 'Rename', 'mutation');
      expect(
          code,
          contains('typedef RunRenameMutation = '
              'graphql.MultiSourceResult<Rename_Rename?> Function(\n'
              '    RenameVariables variables, {Object? optimisticResult});\n'));
      expect(code,
          contains('class RenameMutation extends widgets.StatelessWidget {\n'));
      // Variables and the optimistic result are given per run.
      expect(
          code,
          contains('  const RenameMutation({\n'
              '    super.key,\n'
              '    this.fetchPolicy,\n'));
      expect(code, isNot(contains('this.variables')));
      expect(code, isNot(contains('this.optimisticResult')));
      expect(
          code,
          contains('  final widgets.Widget Function(RunRenameMutation '
              'runMutation, graphql.QueryResult<Rename_Rename?>? result) '
              'builder;\n'));
      expect(
          code,
          contains(
              '    final options = graphql.MutationOptions<Rename_Rename?>(\n'
              '      document: renameDocument,\n'
              '      operationName: renameOperationName,\n'));
      expect(code, contains('      parserFn: parseRenameData,\n'));
      expect(
          code,
          contains('builder((variables, {optimisticResult}) => '
              'runMutation(variables.toJson(), '
              'optimisticResult: optimisticResult), result);\n'));
    });

    test('mutations without or with optional variables', () {
      final ping = _generate('mutation Ping { ping }', 'Ping', 'mutation');
      expect(
          ping,
          contains('typedef RunPingMutation = graphql.MultiSourceResult<bool?> '
              'Function(\n    {Object? optimisticResult});\n'));
      expect(
          ping,
          contains('({optimisticResult}) => runMutation(const {}, '
              'optimisticResult: optimisticResult)'));

      final touch = _generate(
          r'mutation Touch($at: Int) { touch(at: $at) }', 'Touch', 'mutation');
      expect(
          touch,
          contains('Function(\n'
              '    {TouchVariables? variables, Object? optimisticResult});\n'));
      expect(
          touch,
          contains('({variables, optimisticResult}) => '
              'runMutation(variables?.toJson() ?? const {}, '
              'optimisticResult: optimisticResult)'));
    });

    test('a subscription gets a widget wrapping Subscription', () {
      final code = _generate(_userChanged, 'UserChanged', 'subscription');
      expect(
          code,
          contains('class UserChangedSubscription extends '
              'widgets.StatelessWidget {\n'));
      expect(code, contains('    this.variables,\n'));
      expect(code, contains('    this.optimisticResult,\n'));
      expect(
          code,
          contains('  final graphql_flutter.OnSubscriptionResult'
              '<UserChanged_UserChanged>? onSubscriptionResult;\n'));
      expect(
          code,
          contains('  final graphql_flutter.SubscriptionBuilder'
              '<UserChanged_UserChanged> builder;\n'));
      expect(
          code,
          contains('    final options = userChangedSubscriptionOptions(\n'
              '      variables: variables,\n'));
      expect(code,
          contains('graphql_flutter.Subscription<UserChanged_UserChanged>('));
      expect(
          code,
          contains(
              'graphql_flutter.SubscriptionOnClient<UserChanged_UserChanged>('));
    });

    test('a widget named like a schema type is an error', () {
      expect(
          () => _generate('query User { version }', 'User', 'query'),
          throwsA(isA<CodegenException>()
              .having((e) => e.code, 'code',
                  CodegenErrorCodes.buildDuplicateDeclaration)
              .having((e) => e.message, 'message', contains('"UserQuery"'))));
    });

    test('widget names are declarations the builder checks', () {
      final names =
          topLevelDeclarations(_generate(_rename, 'Rename', 'mutation'));
      expect(names, containsAll(['RenameMutation', 'RunRenameMutation']));
    });
  });

  group('flutter_hooks', () {
    setUp(() => CodegenConfigContext.flutterHooks = true);

    test('import only graphql_flutter', () {
      final code = _generate(_getUser, 'GetUser', 'query');
      expect(code, isNot(contains('package:flutter/')));
      expect(
          code,
          contains("import 'package:graphql_flutter/graphql_flutter.dart' "
              'as graphql_flutter;\n'));
      expect(code, isNot(contains('class GetUserQuery')));
    });

    test('a query gets useQuery and useWatchQuery hooks', () {
      final code = _generate(_getUser, 'GetUser', 'query');
      expect(
          code,
          contains('graphql_flutter.QueryHookResult<GetUser_User?> '
              'useGetUserQuery(\n'
              '  GetUserVariables variables, {\n'
              '  graphql.FetchPolicy? fetchPolicy,\n'));
      expect(code, contains('  graphql.OnQueryError? onError,\n}) {\n'));
      expect(
          code,
          contains('  return graphql_flutter.useQuery<GetUser_User?>'
              '(getUserQueryOptions(\n'
              '    variables,\n'));
      expect(
          code,
          contains('graphql.ObservableQuery<GetUser_User?> '
              'useGetUserWatchQuery(\n'
              '  GetUserVariables variables, {\n'));
      expect(code, contains('  bool fetchResults = false,\n'));
      expect(
          code,
          contains('  return graphql_flutter.useWatchQuery<GetUser_User?>'
              '(getUserWatchQueryOptions(\n'));
    });

    test('hooks without variables', () {
      final code = _generate('query Version { version }', 'Version', 'query');
      expect(
          code,
          contains('graphql_flutter.QueryHookResult<String?> '
              'useVersionQuery({\n'
              '  graphql.FetchPolicy? fetchPolicy,\n'));
    });

    test('a mutation hook returns a typed run function and the result', () {
      final code = _generate(_rename, 'Rename', 'mutation');
      expect(code, contains('typedef RunRenameMutation ='));
      expect(
          code,
          contains('({RunRenameMutation runMutation, '
              'graphql.QueryResult<Rename_Rename?> result}) '
              'useRenameMutation({\n'
              '  graphql.FetchPolicy? fetchPolicy,\n'));
      expect(
          code,
          contains('  final mutation = graphql_flutter.useMutation'
              '<Rename_Rename?>(graphql.MutationOptions<Rename_Rename?>(\n'));
      expect(
          code,
          contains('    runMutation: (variables, {optimisticResult}) => '
              'mutation.runMutation(variables.toJson(), '
              'optimisticResult: optimisticResult),\n'
              '    result: mutation.result,\n'));
    });

    test('a subscription hook returns the latest result', () {
      final code = _generate(_userChanged, 'UserChanged', 'subscription');
      expect(
          code,
          contains('graphql.QueryResult<UserChanged_UserChanged> '
              'useUserChangedSubscription({\n'
              '  UserChangedVariables? variables,\n'));
      expect(
          code,
          contains('  graphql_flutter.OnSubscriptionResult'
              '<UserChanged_UserChanged>? onSubscriptionResult,\n}) {\n'));
      expect(
          code, contains('    onSubscriptionResult: onSubscriptionResult,\n'));
    });

    test('hook names are declarations the builder checks', () {
      final names =
          topLevelDeclarations(_generate(_getUser, 'GetUser', 'query'));
      expect(names, containsAll(['useGetUserQuery', 'useGetUserWatchQuery']));
    });
  });

  test('result_types: schema uses the schema types', () {
    CodegenConfigContext.resultTypes = 'schema';
    CodegenConfigContext.flutterWidgets = true;
    CodegenConfigContext.flutterHooks = true;
    final query = _generate(_getUser, 'GetUser', 'query');
    expect(query,
        contains('final graphql_flutter.QueryBuilder<User?> builder;\n'));
    expect(query,
        contains('graphql_flutter.QueryHookResult<User?> useGetUserQuery('));
    final mutation = _generate(_rename, 'Rename', 'mutation');
    expect(
        mutation,
        contains('typedef RunRenameMutation = '
            'graphql.MultiSourceResult<User?> Function('));
  });
}
